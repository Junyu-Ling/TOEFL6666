function buildRaw(text, pairs) {
  let raw = text;
  for (const [word, fill] of pairs) {
    const token = `{${word}|${fill}}`;
    if (!raw.includes(token)) throw new Error(`Token not found: ${token}`);
    raw = raw.replace(token, blank(word, fill));
  }
  if (raw.includes("{")) throw new Error(`Unreplaced tokens in: ${raw}`);
  return raw;
}

