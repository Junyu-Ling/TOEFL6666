function toEntries(pairs) {
  return pairs.map(([word, definition]) => ({ word, definitions: [definition] }));
}

const manifestPath = path.join(dir, "manifest.json");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
manifest.lists = (manifest.lists ?? []).filter((item) => item.book !== "jingjing");
manifest.updatedAt = updatedAt;

for (const book of BOOKS) {
  const id = `jingjing-${book.year}`;
  const words = toEntries(book.words);
  const title = `SAT鸡精 · ${book.year}`;
  const payload = {
    meta: {
      level: book.year,
      list: 1,
      title,
      book: "jingjing",
      year: book.year,
      updatedAt,
    },
    words,
  };
  fs.writeFileSync(path.join(dir, `${id}.json`), `${JSON.stringify(payload, null, 2)}\n`);
  manifest.lists.push({
    id,
    title,
    level: book.year,
    list: 1,
    book: "jingjing",
    year: book.year,
    wordCount: words.length,
  });
  console.log(`${title}: ${words.length} words`);
}

fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
